/**
 * Generate src/settings/brand-svg.ts from simple-icons (CC0-1.0).
 *
 * Run with: node scripts/gen-brand-icons.mjs   (needs `npm i --no-save simple-icons`)
 *
 * WHY GENERATE RATHER THAN DEPEND. simple-icons is ~3,300 icons; we need a
 * dozen. Extracting the paths into a checked-in file keeps the marks offline
 * (the app's CSP blocks remote images, and an icon that needs the network is a
 * blank square on a plane) with no runtime dependency and no bundle cost.
 *
 * WHY NOT EVERY BRAND WE LIST. Two are deliberately absent:
 *   - OpenAI / Codex: not in simple-icons, which is downstream of OpenAI
 *     enforcing its trademark. We do not draw our own imitation.
 *   - Hermes (Nous Research): simple-icons' `siHermes` is the PARCEL COMPANY.
 *     Shipping a courier's logo next to an AI agent is a worse error than
 *     shipping no logo, so that one stays a neutral glyph.
 * A wrong mark is worse than a missing one; both fall back to a monogram.
 */
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

/** local id → simple-icons export. Only marks we are confident are correct. */
const WANT = {
  'claude-code': 'siClaude',
  opencode: 'siOpencode',
  huggingface: 'siHuggingface',
  nvidia: 'siNvidia',
  qwen: 'siQwen',
  deepseek: 'siDeepseek',
  ollama: 'siOllama',
  meta: 'siMeta',
  google: 'siGoogle',
  mistralai: 'siMistralai',
  minimax: 'siMinimax',
  kimi: 'siKimi',
  moonshotai: 'siMoonshotai',
  // Devices (track 5): the tailnet the Devices panel is built on. Its own
  // mark, never a drawing of one (devices-tailscale.md §3; the W0-A glyph batch).
  tailscale: 'siTailscale',
};

const rows = [];
/* Dynamic access is the point: this is a BUILD script that looks up icons by a
   name from a table, and the tree-shaking the rule protects does not apply to a
   script that runs once and writes a file. */
for (const [id, key] of Object.entries(WANT)) {
  // biome-ignore lint/performance/noDynamicNamespaceImportAccess: a build script, by name, on purpose.
  const icon = si[key];
  if (icon === undefined) {
    console.error(`missing ${key}; skipping ${id}`);
    continue;
  }
  rows.push(
    `  ${JSON.stringify(id)}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(
      `#${icon.hex}`,
    )}, path: ${JSON.stringify(icon.path)} },`,
  );
}

writeFileSync(
  'src/settings/brand-svg.ts',
  `/**
 * GENERATED by scripts/gen-brand-icons.mjs — do not edit by hand.
 *
 * Official brand marks extracted from simple-icons (CC0-1.0). The paths are the
 * vendors' own artwork, used to identify their product in a list; the icon
 * COLLECTION is CC0, the marks themselves remain their owners' trademarks and
 * their presence implies no endorsement.
 *
 * Deliberately absent, because a wrong mark is worse than none:
 *   - OpenAI / Codex — not in simple-icons (trademark enforcement). No imitation.
 *   - Hermes (Nous Research) — simple-icons' \`siHermes\` is the parcel company.
 * Both fall back to a monogram at the call site.
 */

export interface BrandSvg {
  readonly title: string;
  readonly hex: string;
  /** Single 24x24 path, as simple-icons ships it. */
  readonly path: string;
}

export const BRAND_SVGS: Readonly<Record<string, BrandSvg>> = {
${rows.join('\n')}
};
`,
);
console.log(`wrote src/settings/brand-svg.ts with ${rows.length} marks`);
